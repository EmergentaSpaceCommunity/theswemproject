// Third-party notices of what the Workbench's page bundles: every package the
// production dependency graph reaches, its licence and its copyright line.
//
// Usage, from the repository root, after `npm ci` in the page's directory:
//   node scripts/third-party-notices.mjs > THIRD-PARTY-NOTICES.md
import fs from "node:fs";
import path from "node:path";
process.chdir(new URL("../crates/swem-host/web/apps-host/", import.meta.url).pathname);
const lock = JSON.parse(fs.readFileSync("package-lock.json", "utf8"));
const pkgs = lock.packages;
const prod = new Set();
const walk = (key) => {
  if (prod.has(key)) return;
  prod.add(key);
  const p = pkgs[key];
  for (const dep of Object.keys({...(p.dependencies ?? {}), ...(p.optionalDependencies ?? {})})) {
    // npm resolves a dependency from the deepest `node_modules` up to the root.
    const levels = key.split("/node_modules/");
    let k = null;
    for (let n = levels.length; n >= 0 && k === null; n -= 1) {
      const base = levels.slice(0, n).join("/node_modules/");
      const candidate = base ? `${base}/node_modules/${dep}` : `node_modules/${dep}`;
      if (candidate in pkgs) k = candidate;
    }
    if (k !== null) walk(k);
  }
};
for (const dep of Object.keys(pkgs[""].dependencies ?? {})) walk(`node_modules/${dep}`);
prod.delete("");
const rows = [];
for (const key of [...prod].sort()) {
  const p = pkgs[key];
  const name = key.replace(/^.*node_modules\//, "");
  let copyright = "";
  const dir = path.join(process.cwd(), key);
  for (const f of ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "LICENSE-MIT", "license", "License.md"]) {
    const fp = path.join(dir, f);
    if (fs.existsSync(fp)) {
      const m = fs.readFileSync(fp, "utf8").match(/^.*copyright.*$/im);
      if (m) copyright = m[0].trim().replace(/\s+/g, " "); break;
    }
  }
  rows.push({name, version: p.version, license: p.license ?? "", copyright});
}
let out = `# Third-party notices\n\nWhat the Workbench's page (\`crates/swem-host/web/apps-host/dist/workbench.js\`, carried by the\n\`swem\` binary) bundles: every package its production dependency graph reaches, with its licence\nand the copyright line of its licence file, as \`package-lock.json\` names it. Generated by\n\`scripts/third-party-notices.mjs\`; regenerate it when the page's dependencies change. The full\nlicence text of each package is in its own source under \`node_modules\` after \`npm ci\`.\n\nRust crate dependencies are named with their licences in \`Cargo.lock\`'s packages; each carries\nits licence text in its own source.\n\n| Package | Version | Licence | Copyright |\n|---|---|---|---|\n`;
for (const r of rows) out += `| ${r.name} | ${r.version} | ${r.license} | ${r.copyright.replace(/\|/g, "\\|")} |\n`;
process.stdout.write(out);
const counts = {}; for (const r of rows) counts[r.license] = (counts[r.license] ?? 0) + 1;
console.error(rows.length, "packages", counts);
